export type LabelKey = keyof typeof ENGLISH;

const TABLES: Record<UiLanguage, { [Key in LabelKey]: string }> = {
  en: ENGLISH,
  am: AMHARIC,
};

/** Interface language from the host `lang` value. Unsupported values use English. */
export function uiLanguage(lang: string | null | undefined): UiLanguage {
  const value = (lang ?? '').trim().toLowerCase();
  if (value === 'am' || value.startsWith('am-')) return 'am';
  return 'en';
}

export function interfaceText(
  lang: string | null | undefined,
  key: LabelKey,
  values?: Record<string, string | number>,
): string {
  const template = TABLES[uiLanguage(lang)][key];
  if (values === undefined) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const replacement = values[name];
    return replacement === undefined ? match : String(replacement);
  });
}
